  "不使用位图与外部引用。";
const FORBIDDEN_BASE = "【禁止】文字、旗帜、徽记、标语、真实人物、JavaScript 与交互事件";

function composeLandmarkPrompt(parts: LandmarkPromptParts): string {
  return (
    "生成一幅 SVG 插画。" +
    `【主体】${parts.subject}` +
    `【结构】${parts.structure}` +
    `【比例】${parts.proportion}` +
    `【材质与色彩】${parts.material}` +
    `【环境与微缩细节】${parts.environment}` +
    COMPOSITION +
    LIGHTING +
    DEPTH +
    DETAIL +
    ATMOSPHERE +
    STYLE +
    `${FORBIDDEN_BASE}、${parts.forbidden}。`
  );
}

